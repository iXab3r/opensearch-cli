// Renders inventory facts as GitHub issue titles, bodies and labels. Facts only: no design or priority.
const PRACTICE = "https://github.com/iXab3r/EyeAuras.CliFactory/blob/main/docs/practices/story-driven-delivery.md";

export const groupMarker = (group) => `<!-- api-inventory:group:${group.name} -->`;
export const operationMarker = (operation) => `<!-- api-inventory:operation:${operation.id} -->`;

const short = (revision) => revision.slice(0, 7);
const sourceLink = (inventory, file) =>
  `[opensearch-api-specification@${short(inventory.source.revision)}](${inventory.source.repository}/blob/${inventory.source.revision}/${file})`;
const yesNo = (value) => (value ? "yes" : "no");
const cell = (value) => (value === null ? "—" : value);

export function groupTitle(group) {
  return `API group: ${group.name}`;
}

export function operationTitle(operation) {
  return `api: ${operation.id}`;
}

export function groupLabels(group) {
  return ["type:api-group", `api:${group.name}`];
}

export function operationLabels(group, operation, inventory) {
  const labels = ["type:api", `api:${group.name}`];
  const [oldest, ...rest] = inventory.supportedMajors;
  const onlyNewest = rest.length > 0 && !operation.availability[`${oldest}.x`]
    && operation.availability[`${rest.at(-1)}.x`];
  if (onlyNewest) labels.push(`os:${rest.at(-1)}.x-only`);
  if (!Object.values(operation.availability).some(Boolean)) labels.push("os:unsupported");
  if (operation.deprecated !== null) labels.push("deprecated");
  return labels;
}

export function groupBody(group, inventory) {
  const availability = inventory.supportedMajors.map((major) => {
    const count = group.operations.filter((op) => op.availability[`${major}.x`]).length;
    return `${major}.x: ${count}`;
  }).join(" · ");
  return [
    groupMarker(group),
    `**${group.title}**: progress tracker for the \`${group.name}\` API group.`,
    "",
    `- Operations: **${group.operations.length}** (available in OpenSearch ${availability})`,
    `- Source: ${sourceLink(inventory, group.file)}`,
    "",
    "Each operation is a sub-issue. This group is a progress tracker, not a work order: operations are",
    "delivered through user stories, and an operation closes when a delivered story uses it with tested",
    `behavior or on an explicit owner *won't do* decision. See [story-driven delivery](${PRACTICE}).`,
    "",
    "_Generated by `tools/api-inventory`. Edit the generator or the pinned revision, not this text._",
  ].join("\n");
}

export function operationBody(group, operation, inventory) {
  const rows = operation.endpoints.map((e) =>
    `| \`${e.method}\` | \`${e.path}\` | ${cell(e.added)} | ${cell(e.deprecated)} | ${cell(e.removed)} |`);
  const availability = inventory.supportedMajors
    .map((major) => `${major}.x: ${yesNo(operation.availability[`${major}.x`])}`).join(" · ");
  const docs = operation.docs.length === 0 ? ["- Documentation: none in the specification"]
    : operation.docs.map((url) => `- Documentation: ${url}`);
  return [
    operationMarker(operation),
    `**Operation:** \`${operation.id}\` · **Group:** \`${group.name}\``,
    "",
    operation.description ? `> ${operation.description.replace(/\s*\n\s*/g, " ")}` : "> No description in the specification.",
    "",
    "| Method | Path | Added | Deprecated | Removed |",
    "|---|---|---|---|---|",
    ...rows,
    "",
    `- Available in OpenSearch ${availability}`,
    ...docs,
    `- Source: ${sourceLink(inventory, group.file)}`,
    "",
    "Inventory item. Closes when a delivered story uses this operation with tested behavior, or on an",
    "explicit owner *won't do* decision with a reason.",
    "",
    "_Generated by `tools/api-inventory`. Edit the generator or the pinned revision, not this text._",
  ].join("\n");
}
